category = input("Введите категорию (напиток, суп, десерт): ")

match category:
    case "напиток":
        print("Варианты: чай, кофе, сок")
    case "суп":
        print("Варианты: борщ, щи, суп-пюре")
    case "десерт":
        print("Варианты: торт, мороженое, фрукты")
    case _:
        print("Такой категории нет")
        exit()  # дальше спрашивать блюдо нет смысла

food = input("Введите блюдо: ")

match food:
    case "чай" | "кофе" | "сок":
        print("Цена за напиток 10 руб")
    case "борщ" | "щи" | "суп-пюре":
        print("Цена за суп 30 руб")
    case "торт" | "мороженое" | "фрукты":
        print("Цена за десерт 15 руб")
    case _:
        print("Такого блюда нет у нас")